import mongoose from 'mongoose';

const slotSchema = new mongoose.Schema(
  {
    slotId: { type: String, required: true, unique: true, trim: true }, // e.g. "A-101"
    zone: { type: String, required: true, trim: true }, // e.g. "Zone A"
    floor: { type: Number, required: true, min: 0 },
    // Physical state, written by the IoT sensor. "reserved" is computed from bookings, not stored.
    status: { type: String, enum: ['available', 'occupied', 'maintenance'], default: 'available' },
    // Who controls this slot's status. "manual" = an admin set it, sensors must not overwrite it.
    controlMode: { type: String, enum: ['auto', 'manual'], default: 'auto' },
    // PARQCO uses virtual sensors only. "real" is kept for a future ESP32 device.
    sensorType: { type: String, enum: ['virtual', 'real'], default: 'virtual' },
    // Where this slot came from: the seed, an admin, or auto-generated by the system when the lot was full.
    slotSource: { type: String, enum: ['seed', 'admin', 'auto-system'], default: 'seed' },
    sensorId: { type: String, required: true, unique: true, trim: true }, // e.g. "SENSOR_A101"
    hourlyRate: { type: Number, default: 100, min: 0 }, // PKR per hour
  },
  { timestamps: true }
);

export default mongoose.model('Slot', slotSchema);